/**
 * Writes samples/generated-emails.md from the real renderer for every lead in a campaign (one command, reproducible).
 *   npm run samples -- <campaignId>
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pool } from '../src/db/pool.js';
import { previewOutreach } from '../src/modules/email/email.service.js';

const campaignId = Number(process.argv[2] ?? 1);
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../samples/generated-emails.md');

const { rows: leads } = await pool.query(
  `SELECT l.id, l.first_name, l.last_name, l.title, l.source_url, c.name AS company
     FROM campaign_leads cl JOIN leads l ON l.id = cl.lead_id JOIN companies c ON c.id = l.company_id
    WHERE cl.campaign_id = $1 ORDER BY l.id`,
  [campaignId],
);
if (!leads.length) throw new Error(`Campaign ${campaignId} has no leads`);

const sections = [];
for (const lead of leads) {
  const p = await previewOutreach(campaignId, lead.id);
  const name = [lead.first_name, lead.last_name].filter(Boolean).join(' ');
  const lines = [`## ${name} - ${lead.title}, ${lead.company}`, '', `Lead source: ${lead.source_url}`, ''];
  if (p.blocked) {
    lines.push(`**Blocked by the grounding check:** ${p.blockReason}`, '');
  } else {
    lines.push(`**Subject:** ${p.subject}`, '', '```text', [...p.paragraphs, p.signOff.join('\n')].join('\n\n'), '```', '');
  }
  lines.push('| Token | Value | Source |', '|---|---|---|');
  for (const t of p.tokens) {
    lines.push(`| \`${t.token}\` | ${t.value} | ${t.sourceUrl ? `[${t.source}](${t.sourceUrl})` : t.source} |`);
  }
  if (p.log.length) {
    lines.push('', 'Grounding log:', ...p.log.map((l) => `- \`${l.token}\` ${l.rule}: ${l.detail} -> **${l.action}**`));
  }
  sections.push(lines.join('\n'));
}

const header = `# Sample outreach emails

Generated by \`npm run samples -- ${campaignId}\` from leads found by the discovery agent (real public pages).
Every token is filled from a stored lead/company/campaign field, a source-cited company signal, or StyleSense's fixed
product copy. The footer (unsubscribe link + tracking pixel) is added at send time and omitted here.
`;
await mkdir(path.dirname(out), { recursive: true });
await writeFile(out, `${header}\n${sections.join('\n\n---\n\n')}\n`);
console.log(`wrote ${leads.length} emails to ${path.relative(process.cwd(), out)}`);
await pool.end();
